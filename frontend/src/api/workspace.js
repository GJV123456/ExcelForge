import request from '../utils/request'

export const getWorkspaceContext = (params) => request.get('/api/workspace/context', { params })
export const getWorkspaceConfigs = (params) => request.get('/api/workspace/configs', { params })
export const createWorkspaceConfig = (data) => request.post('/api/workspace/configs', data)
export const updateWorkspaceConfig = (id, data) => request.put(`/api/workspace/configs/${id}`, data)
export const copyWorkspaceConfig = (data) => request.post('/api/workspace/configs/copy', data)
export const batchCopyWorkspaceConfigs = (data) => request.post('/api/workspace/configs/batch-copy', data)
export const importWorkspaceConfigs = (data) => request.post('/api/workspace/configs/import', data)
export const setWorkspaceConfigStatus = (id, enabled) => request.post(`/api/workspace/configs/${id}/status`, null, { params: { enabled } })
export const downloadWorkspaceTemplate = () => request.get('/api/workspace/template', { responseType: 'blob' })
export const downloadWorkspaceConfigTemplate = (params) => request.get('/api/workspace/config-template', { params, responseType: 'blob' })
export const getWorkspaceCatalog = (params) => request.get('/api/workspace/catalog', { params })
export const saveWorkspaceCatalog = (id, data) => id
  ? request.put(`/api/workspace/catalog/${id}`, data)
  : request.post('/api/workspace/catalog', data)
export const setWorkspaceCatalogStatus = (id, enabled, scope) => request.post(`/api/workspace/catalog/${id}/status`, null, { params: { ...scope, enabled } })
export const getWorkspaceUsers = () => request.get('/api/workspace/users')
export const createWorkspaceUser = (data) => request.post('/api/workspace/users', data)
export const updateWorkspaceUser = (id, data) => request.put(`/api/workspace/users/${id}`, data)
export const createWorkspaceLine = (data) => request.post('/api/workspace/lines', data)
export const updateWorkspaceLine = (id, data) => request.put(`/api/workspace/lines/${id}`, data)
export const createWorkspaceProfession = (data) => request.post('/api/workspace/professions', data)
export const updateWorkspaceProfession = (id, data) => request.put(`/api/workspace/professions/${id}`, data)
export const createWorkspaceProject = (data) => request.post('/api/workspace/projects', data)
export const updateWorkspaceProject = (id, data) => request.put(`/api/workspace/projects/${id}`, data)
